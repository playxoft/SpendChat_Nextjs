/**
 * Consumer price index by country, for `/tools/inflation-calculator`.
 *
 * World Bank indicator FP.CPI.TOTL — "Consumer price index (2010 = 100)",
 * annual averages — as published in the World Development Indicators
 * (dataset last updated 2026-07-13) and snapshotted on `CPI_FETCHED_ON`.
 * Licensed CC BY 4.0: the page must credit the World Bank and link to the
 * source, which `CPI_SOURCE` carries.
 *
 * Refresh once a year, after the World Bank publishes the last full year
 * (usually by mid-year):
 *
 *   https://api.worldbank.org/v2/country/IND;USA;GBR/indicator/FP.CPI.TOTL?format=json&per_page=20000&date=1960:2030
 *
 * (the API rejects long country lists — fetch in batches of about six), keep
 * every value to 6 significant figures, bump `CPI_FETCHED_ON`, and re-check
 * the spot values in `tests/unit/tools/inflation.test.ts`.
 *
 * A country's series starts at the later of its first published year and the
 * year its current currency began (Brazil's real in 1994, Türkiye's new lira
 * in 2005…): an index can run back through a redenomination, but "R$100 in
 * 1980" can't — the real didn't exist. Euro-area countries are the exception:
 * the old currencies converted at a fixed rate, so earlier years stay, and
 * `note` gives the rate.
 *
 * Deliberately 20 countries, not every one the World Bank covers: the
 * calculator compares them side by side and lists all of them in one table,
 * and this file ships in the page's JavaScript. The set is mostly the G20
 * economies, plus Spain, Singapore and the UAE; the tests pin it, so a change
 * is deliberate. A country is only added if its series has no gap.
 */

