export type CpiCountry = {
  /** ISO 3166-1 alpha-2. */
  country: string;
  name: string;
  /** ISO 4217 — amounts for this country are read in its currency. */
  currency: string;
  /** The World Bank page for this country's series. */
  source: string;
  firstYear: number;
  /** The last full year the World Bank has published for this country. */
  lastYear: number;
  /** Shown under the country when the series needs explaining (currency changes). */
  note?: string;
  /** Index by year, 2010 = 100 — one entry for every year firstYear..lastYear. */
  values: Readonly<Record<number, number>>;
};

/** A run of yearly values from `first` onwards, as a year-keyed record. */
function series(first: number, values: number[]): Record<number, number> {
  const out: Record<number, number> = {};
  values.forEach((v, i) => {
    out[first + i] = v;
  });
  return out;
}

