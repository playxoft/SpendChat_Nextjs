/** Every country, sorted by name as the country picker lists them. */
export const CPI_COUNTRIES: readonly CpiCountry[] = ENTRIES.map((e) => ({
  ...e,
  source: `${CPI_SOURCE.url}?locations=${e.country}`,
})).sort((a, b) => a.name.localeCompare(b.name, "en"));

const BY_CODE = new Map(CPI_COUNTRIES.map((c) => [c.country, c]));

/** A country's series by ISO code (any case), or null when we don't have it. */
export function findCpiCountry(code: string | null | undefined): CpiCountry | null {
  if (!code) return null;
  return BY_CODE.get(code.trim().toUpperCase()) ?? null;
}
